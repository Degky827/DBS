#!/usr/bin/env bash
# Generates a fresh production .env for the Docker Compose stack.
#
# Refuses to overwrite an existing file: a redeploy must keep the secrets that
# already encrypt stored KYC documents and sign refresh tokens.
#
# The Brevo key is required because auth-service exits in production without it
# (registration and password reset could not deliver email). Pass it through a
# file to keep it out of shell history:
#
#   sudo BREVO_API_KEY_FILE=/root/brevo.key \
#     deploy/oracle/generate-env.sh --app-dir /opt/banking-system --domain bank.example.com
set -euo pipefail

APP_DIR=""
DOMAIN=""
POSTGRES_USER="${POSTGRES_USER:-meridian}"

usage() {
    cat <<'EOF'
Usage: generate-env.sh --app-dir DIR --domain HOST [options]

  --app-dir DIR    repository checkout that will hold .env (required)
  --domain HOST    public DNS name; APP_ORIGIN becomes https://HOST (required)

Environment:
  BREVO_API_KEY_FILE   file containing the Brevo REST (xkeysib-) or SMTP
                       (xsmtpsib-) key; preferred over BREVO_API_KEY
  BREVO_API_KEY        same value inline (visible in the process environment)
  EMAIL_TRANSPORT      "api" or "smtp"; inferred from the key prefix when unset
  EMAIL_FROM           display name (default "Meridian Bank")
  EMAIL_FROM_EMAIL     sender address (default no-reply@HOST)
  EMAIL_SMTP_USER      SMTP login when EMAIL_TRANSPORT=smtp
  DIDIT_API_KEY, DIDIT_WORKFLOW_ID, DIDIT_WEBHOOK_SECRET
                       optional KYC provider settings; KYC session creation
                       stays disabled while they are empty
  CHAPA_SECRET_KEY, CHAPA_WEBHOOK_SECRET
                       optional Chapa test-mode settings; deposits stay
                       disabled while CHAPA_SECRET_KEY is empty
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --app-dir) APP_DIR="${2:-}"; shift 2 ;;
        --domain) DOMAIN="${2:-}"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
done

[ -n "$APP_DIR" ] || { echo "--app-dir is required." >&2; exit 2; }
[ -n "$DOMAIN" ] || { echo "--domain is required." >&2; exit 2; }
case "$DOMAIN" in
    *[!A-Za-z0-9.-]*|.*|*.) echo "Invalid domain: $DOMAIN" >&2; exit 2 ;;
esac

command -v openssl >/dev/null 2>&1 || { echo "openssl is required." >&2; exit 1; }
[ -d "$APP_DIR" ] || { echo "App directory not found: $APP_DIR" >&2; exit 1; }

ENV_FILE="$APP_DIR/.env"
if [ -e "$ENV_FILE" ]; then
    echo "Refusing to overwrite $ENV_FILE. Existing secrets are preserved." >&2
    exit 1
fi

if [ -n "${BREVO_API_KEY_FILE:-}" ]; then
    [ -r "$BREVO_API_KEY_FILE" ] || { echo "BREVO_API_KEY_FILE is not readable." >&2; exit 1; }
    BREVO_API_KEY="$(tr -d '\r\n' < "$BREVO_API_KEY_FILE")"
else
    BREVO_API_KEY="${BREVO_API_KEY:-}"
fi
if [ -z "$BREVO_API_KEY" ]; then
    cat >&2 <<'EOF'
BREVO_API_KEY is required: auth-service refuses to start in production without
it. Create a key at https://app.brevo.com, store it in a root-only file, and
pass BREVO_API_KEY_FILE=/path/to/file.
EOF
    exit 1
fi

case "$BREVO_API_KEY" in
    xkeysib-*) DEFAULT_TRANSPORT="api" ;;
    xsmtpsib-*) DEFAULT_TRANSPORT="smtp" ;;
    *) echo "BREVO_API_KEY must start with xkeysib- or xsmtpsib-." >&2; exit 1 ;;
esac
EMAIL_TRANSPORT="${EMAIL_TRANSPORT:-$DEFAULT_TRANSPORT}"
if [ "$EMAIL_TRANSPORT" = "api" ] && [ "${BREVO_API_KEY#xkeysib-}" = "$BREVO_API_KEY" ]; then
    echo "EMAIL_TRANSPORT=api requires a REST key (xkeysib-)." >&2
    exit 1
fi
if [ "$EMAIL_TRANSPORT" = "smtp" ] && [ "${BREVO_API_KEY#xsmtpsib-}" = "$BREVO_API_KEY" ]; then
    echo "EMAIL_TRANSPORT=smtp requires an SMTP key (xsmtpsib-)." >&2
    exit 1
fi

EMAIL_FROM="${EMAIL_FROM:-Meridian Bank}"
EMAIL_FROM_EMAIL="${EMAIL_FROM_EMAIL:-no-reply@$DOMAIN}"
EMAIL_SMTP_USER="${EMAIL_SMTP_USER:-}"

CHAPA_SECRET_KEY="${CHAPA_SECRET_KEY:-}"
CHAPA_WEBHOOK_SECRET="${CHAPA_WEBHOOK_SECRET:-}"
if [ -n "$CHAPA_SECRET_KEY" ] && [ -z "$CHAPA_WEBHOOK_SECRET" ]; then
    echo "CHAPA_WEBHOOK_SECRET is required when CHAPA_SECRET_KEY is set." >&2
    exit 1
fi

umask 077
POSTGRES_PASSWORD="$(openssl rand -hex 24)"
REDIS_PASSWORD="$(openssl rand -hex 24)"
JWT_SECRET="$(openssl rand -hex 64)"
INTERNAL_SERVICE_KEY="$(openssl rand -hex 32)"
STORAGE_ENCRYPTION_KEY="$(openssl rand -hex 32)"
MFA_ENCRYPTION_KEY="$(openssl rand -hex 32)"

{
    cat <<EOF
# Generated by deploy/oracle/generate-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Contains secrets: mode 600, never commit, back up securely.
APP_ORIGIN=https://$DOMAIN
TLS_ENABLED=true
FRONTEND_HTTP_PORT=80
FRONTEND_HTTPS_PORT=443

POSTGRES_USER=$POSTGRES_USER
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
REDIS_PASSWORD=$REDIS_PASSWORD
REDIS_MAXMEMORY=128mb

JWT_ALGORITHM=HS256
JWT_SECRET=$JWT_SECRET
JWT_PRIVATE_KEY_BASE64=
JWT_PUBLIC_KEY_BASE64=
JWT_KEY_ID=
JWT_EXPIRES_IN=15m
JWT_ISSUER=auth-service
JWT_AUDIENCE=banking-system

INTERNAL_SERVICE_KEY=$INTERNAL_SERVICE_KEY
STORAGE_ENCRYPTION_KEY=$STORAGE_ENCRYPTION_KEY
STORAGE_ENCRYPTION_KEYS_PREVIOUS=
MFA_ENCRYPTION_KEY=$MFA_ENCRYPTION_KEY
MFA_ISSUER=Meridian Bank
MFA_CHALLENGE_TTL_MS=300000
STEP_UP_TTL_MS=600000

BREVO_API_KEY=$BREVO_API_KEY
EMAIL_TRANSPORT=$EMAIL_TRANSPORT
EMAIL_FROM=$EMAIL_FROM
EMAIL_FROM_EMAIL=$EMAIL_FROM_EMAIL
EMAIL_SMTP_USER=$EMAIL_SMTP_USER
EMAIL_SMTP_HOST=smtp-relay.brevo.com
EMAIL_SMTP_PORT=587
EMAIL_ENABLED=true
BREVO_API_BASE_URL=https://api.brevo.com/v3
EMAIL_TIMEOUT_MS=8000
EMAIL_RETRY_INTERVAL_MS=30000
EMAIL_MAX_ATTEMPTS=6
NOTIFICATION_PAGE_SIZE=20
INTERNAL_RATE_LIMIT_MAX=300

DIDIT_API_KEY=${DIDIT_API_KEY:-}
DIDIT_WORKFLOW_ID=${DIDIT_WORKFLOW_ID:-}
DIDIT_WEBHOOK_SECRET=${DIDIT_WEBHOOK_SECRET:-}
DIDIT_WEBHOOK_SECRET_PREVIOUS=

CHAPA_SECRET_KEY=$CHAPA_SECRET_KEY
CHAPA_WEBHOOK_SECRET=$CHAPA_WEBHOOK_SECRET
CHAPA_BASE_URL=https://api.chapa.global
CHAPA_CALLBACK_URL=https://$DOMAIN/api/user/payments/chapa/callback
CHAPA_RETURN_URL=https://$DOMAIN/wallet

LOG_LEVEL=info
BCRYPT_ROUNDS=12
RATE_LIMIT_WINDOW_MS=900000
RATE_LIMIT_MAX=300
LOGIN_RATE_LIMIT_MAX=10
SENSITIVE_AUTH_RATE_LIMIT_MAX=20
REFRESH_RATE_LIMIT_MAX=60
AUTH_RATE_LIMIT_MAX=20
REFRESH_TOKEN_TTL_MS=604800000
REFRESH_TOKEN_ABSOLUTE_TTL_MS=2592000000
REFRESH_TOKEN_GRACE_MS=30000
REFRESH_COOKIE_SAME_SITE=lax
UPLOAD_RATE_LIMIT_MAX=10
MAX_FILE_SIZE_BYTES=10485760
STATEMENT_MAX_RANGE_DAYS=366

OUTBOX_ENABLED=true
OUTBOX_INTERVAL_MS=5000
OUTBOX_BATCH_SIZE=25
OUTBOX_MAX_ATTEMPTS=12
SCHEDULED_TRANSFERS_ENABLED=true
SCHEDULED_TRANSFERS_INTERVAL_MS=30000
SCHEDULED_TRANSFERS_BATCH_SIZE=10
LEDGER_VERIFICATION_ENABLED=true
LEDGER_VERIFICATION_INTERVAL_MS=21600000

METRICS_TOKEN=
PROMETHEUS_RETENTION=15d
ALERT_SLACK_WEBHOOK_URL=
ALERT_WEBHOOK_URL=
EOF
} > "$ENV_FILE"

chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE (mode 600)."
echo "Generated: POSTGRES_PASSWORD, REDIS_PASSWORD, JWT_SECRET, INTERNAL_SERVICE_KEY,"
echo "           STORAGE_ENCRYPTION_KEY, MFA_ENCRYPTION_KEY."
echo "APP_ORIGIN=https://$DOMAIN, EMAIL_TRANSPORT=$EMAIL_TRANSPORT."
[ -n "$CHAPA_SECRET_KEY" ] && echo "Chapa test mode configured." || echo "Chapa deposits disabled (no key supplied)."
[ -n "${DIDIT_API_KEY:-}" ] && echo "Didit KYC configured." || echo "Didit KYC disabled (no key supplied)."
